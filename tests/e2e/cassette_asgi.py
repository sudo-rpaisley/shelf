def local_png():
    """Generate image bytes locally; no remote artwork or binary fixture needed."""
    import struct
    import zlib

    def chunk(kind, data):
        return (struct.pack("!I", len(data)) + kind + data
                + struct.pack("!I", zlib.crc32(kind + data)))

    pixels = b"".join(b"\0" + bytes((40, 85, 120)) * 16 for _ in range(16))
    return (b"\x89PNG\r\n\x1a\n"
            + chunk(b"IHDR", struct.pack("!2I5B", 16, 16, 8, 2, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(pixels)) + chunk(b"IEND", b""))


class FixtureCatalogue:
    """An exact allowlist, not an all-URLs-return-empty network bypass.

    Unit tests may replace explicit response specifications to exercise errors.
    Unexpected calls are retained as well as raised: provider clients catch
    exceptions, so merely raising AssertionError would not fail their caller.
    """

    def __init__(self, *, audit_path=None):
        self.catalogue = load_catalogue()
        self.audit_path = audit_path
        self.calls = []
        self.unexpected = []
        self.mb_search = {"status": 200, "json": self.catalogue["musicbrainz_empty"]}
        self.discogs_search = {"status": 200, "json": self.catalogue["discogs_search"]}
        self.details = {
            key: {"status": 200, "json": value}
            for key, value in self.catalogue["discogs_releases"].items()
        }

    def _record(self, record):
        import json
        from pathlib import Path

        self.calls.append(record)
        if self.audit_path:
            with Path(self.audit_path).open("a") as stream:
                stream.write(json.dumps(record, sort_keys=True) + "\n")

    def assert_clean(self):
        assert not self.unexpected, f"Unexpected provider requests: {self.unexpected!r}"

    async def fetch(self, client, method, url, **kwargs):
        import httpx
        import re
        from urllib.parse import urlsplit

        parts = urlsplit(str(url))
        params = {str(key): str(value) for key, value in (kwargs.get("params") or {}).items()}
        headers = httpx.Headers(kwargs.get("headers") or {})
        record = {"method": method, "url": str(url), "params": params,
                  "authorization_present": "authorization" in headers}
        # Do not log credential/header values, even in this disposable test app.
        spec = None
        safe = (method == "GET" and parts.scheme == "https" and not parts.username
                and not parts.password and parts.port in (None, 443)
                and not parts.query and not parts.fragment)
        if safe and parts.hostname == "musicbrainz.org" and parts.path == "/ws/2/release/":
            query = params.get("query", "")
            known = self.catalogue["query"]
            manual = self.catalogue["synthetic"]["manual_query"]

            def literal(value):
                return re.sub(r'([+\-!(){}\[\]^"~*?:\\/|&])', r'\\\1', value)

            allowed_query = any(
                f'release:"{literal(choice["title"])}"' in query
                and f'artist:"{literal(choice["artist"])}"' in query
                for choice in (known, manual)
            )
            if allowed_query and "format:Cassette" in query and 'barcode:""' not in query:
                spec = self.mb_search
        elif safe and parts.hostname == "musicbrainz.org":
            release = self.catalogue["synthetic"]["musicbrainz_release"]
            if parts.path == f'/ws/2/release/{release["id"]}':
                spec = {"status": 200, "json": release}
        elif safe and parts.hostname == "coverartarchive.org":
            release = self.catalogue["synthetic"]["musicbrainz_release"]
            if parts.path in {f'/release/{release["id"]}', f'/release-group/{release["release-group"]["id"]}'}:
                spec = {"status": 200, "json": {"images": []}}
        elif safe and parts.hostname == "api.discogs.com" and parts.path == "/database/search":
            known = self.catalogue["query"]
            manual = self.catalogue["synthetic"]["manual_query"]
            allowed = {"release_title", "artist", "type", "format", "per_page", "page", "country", "catno", "barcode"}
            bounded = (params.get("type") == "release" and params.get("format") == "Cassette"
                       and params.get("page") == "1" and params.get("per_page", "").isdigit()
                       and 1 <= int(params["per_page"]) <= 20 and not (set(params) - allowed)
                       and ("barcode" not in params or bool(params["barcode"].strip())))
            if bounded and params.get("release_title") == known["title"] and params.get("artist") == known["artist"]:
                spec = self.discogs_search
            elif bounded and params.get("release_title") == manual["title"] and params.get("artist") == manual["artist"]:
                spec = {"status": 200, "json": self.catalogue["synthetic"]["empty_discogs"]}
        elif safe and parts.hostname == "api.discogs.com" and parts.path.startswith("/releases/"):
            key = parts.path.removeprefix("/releases/")
            if key in self.details and not params:
                spec = self.details[key]
        if spec is None:
            record["unexpected"] = True
            self.unexpected.append(record)
            self._record(record)
            raise AssertionError(f"Fixture does not authorize outbound request: {record!r}")
        self._record(record)
        request = httpx.Request(method, str(url), params=params)
        if "raise" in spec:
            raise spec["raise"]
        options = {"json": spec["json"]} if "json" in spec else {"text": spec["text"]}
        return httpx.Response(spec["status"], headers=spec.get("headers"), request=request, **options)


def create_app():
    """uvicorn tests.e2e.cassette_asgi:create_app --factory."""
    import os

    from app.services import outbound

    fixture = FixtureCatalogue(audit_path=os.environ.get("SHELF_CASSETTE_CALLS"))
    outbound.fetch = fixture.fetch
    # Deliberately only inside the factory, after DATA_DIR/env are established.
    from app.main import app

    app.state.cassette_catalogue = fixture
    return app
